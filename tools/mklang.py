#!/usr/bin/env python3
"""mklang.py language.ini language.h source.c ...

Turns src/language.ini (UTF-8) into the C header of the installer texts:
the keys and the texts of each language in code page 850, kept in far
data (they do not fill the 64 KB data segment of the DOS installer).

Checks that [English] has every key the sources use (T("Key"),
gdi_text("Key") and the error keys archive.c returns) and that no other
section has a key [English] lacks."""
import re
import sys


def read_ini(path):
    sections, order, cur = {}, [], None
    for n, line in enumerate(open(path, encoding='utf-8'), 1):
        line = line.rstrip('\r\n')
        s = line.strip()
        if not s or s.startswith(';'):
            continue
        if s.startswith('[') and s.endswith(']'):
            cur = s[1:-1]
            if cur in sections:
                sys.exit('%s:%d: section [%s] twice' % (path, n, cur))
            sections[cur] = {}
            order.append(cur)
            continue
        if cur is None or '=' not in line:
            sys.exit('%s:%d: not a key=text line' % (path, n))
        key, text = line.split('=', 1)
        key = key.strip()
        if key in sections[cur]:
            sys.exit('%s:%d: %s twice in [%s]' % (path, n, key, cur))
        sections[cur][key] = text
    return sections, order


def c_string(text):
    """a C string literal in code page 850; '\\n' in the INI is a new line"""
    data = text.replace('\\n', '\n').encode('cp850')
    out = []
    for b in data:
        if b == 0x22 or b == 0x5C:
            out.append('\\' + chr(b))
        elif 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            out.append('\\%03o' % b)   # octal: no ambiguity with a digit after it
    return '"' + ''.join(out) + '"'


def used_keys(sources):
    keys = set()
    for path in sources:
        s = open(path, encoding='latin-1').read()
        keys |= set(re.findall(r'\b(?:T|gdi_text)\(\s*"(\w+)"\s*\)', s))
        if path.endswith('archive.c'):
            keys |= set(re.findall(r'return\s+"([A-Z]\w+)"\s*;', s))
    return keys


def main():
    ini, header, sources = sys.argv[1], sys.argv[2], sys.argv[3:]
    sections, order = read_ini(ini)
    if not order or order[0] != 'English':
        sys.exit('%s: [English] must be the first section' % ini)
    english = sections['English']
    meta = ('Country', 'Language')
    keys = sorted(k for k in english if k not in meta)
    missing = sorted(used_keys(sources) - set(keys))
    if missing:
        sys.exit('%s: [English] lacks %s' % (ini, ', '.join(missing)))
    for name in order[1:]:
        extra = sorted(set(sections[name]) - set(english) - set(meta))
        if extra:
            sys.exit('%s: [%s] has keys [English] lacks: %s' % (ini, name, ', '.join(extra)))
    out = ['/* language.h - generated by tools/mklang.py from src/language.ini; do',
           ' * not edit.  The keys in strcmp() order, the texts of each language in',
           ' * code page 850 (NULL: the English text). */', '',
           '#define GDI_TEXTS %d' % len(keys),
           '#define GDI_LANGUAGES %d' % len(order), '']
    # each text an array of its own: a string literal would stay in DGROUP
    for i, k in enumerate(keys):
        out.append('static const char __far gdi_k%d[] = %s;' % (i, c_string(k)))
    out.append('static const char __far *const __far gdi_text_key[GDI_TEXTS] = {')
    out.append('\t' + ', '.join('gdi_k%d' % i for i in range(len(keys))))
    out.append('};')
    out.append('')
    for li, name in enumerate(order):
        for i, k in enumerate(keys):
            t = sections[name].get(k)
            if t is not None:
                out.append('static const char __far gdi_t%d_%d[] = %s;' % (li, i, c_string(t)))
    out.append('static const char __far *const __far gdi_text_of[GDI_LANGUAGES][GDI_TEXTS] = {')
    for li, name in enumerate(order):
        out.append('\t{   /* %s */' % name)
        out.append('\t\t' + ', '.join('gdi_t%d_%d' % (li, i) if k in sections[name] else 'NULL'
                                      for i, k in enumerate(keys)))
        out.append('\t},')
    out.append('};')
    out.append('')
    out.append('/* name, Country= and Language= of each section, "," around each item */')
    for li, name in enumerate(order):
        sec = sections[name]
        out.append('static const char __far gdi_l%d[] = %s;' % (li, c_string(name)))
        out.append('static const char __far gdi_c%d[] = %s;' % (li, c_string(',' + sec.get('Country', '').replace(' ', '') + ',')))
        out.append('static const char __far gdi_s%d[] = %s;' % (li, c_string(',' + sec.get('Language', '').replace(' ', '').lower() + ',')))
    out.append('static const char __far *const __far gdi_language[GDI_LANGUAGES][3] = {')
    for li in range(len(order)):
        out.append('\t{ gdi_l%d, gdi_c%d, gdi_s%d },' % (li, li, li))
    out.append('};')
    open(header, 'w', newline='\n').write('\n'.join(out) + '\n')


main()
